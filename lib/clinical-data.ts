export function diagnosisSuggestions(selectedSigns: string[], species: string) {
  const found = new Set<string>();
  for (const rule of DIAGNOSIS_RULES) {
    if (rule.signs.some((sign) => selectedSigns.includes(sign))) {
      rule.diagnoses.forEach((diagnosis) => found.add(diagnosis));
    }
  }
  if (species === "bird" && selectedSigns.some((sign) => ["خمول", "إفرازات أنفية", "تنفس بفم مفتوح", "إسهال"].includes(sign))) {
    ["عدوى تنفسية في الطيور", "كلاميديا الطيور", "داء الرشاشيات", "اضطراب غذائي", "طفيليات معوية"].forEach((item) => found.add(item));
  }
  if (species === "rabbit" && selectedSigns.includes("فقدان شهية")) {
    ["ركود الجهاز الهضمي", "مرض أسنان", "ألم أو انسداد هضمي"].forEach((item) => found.add(item));
  }
  return Array.from(found).slice(0, 14);
}
